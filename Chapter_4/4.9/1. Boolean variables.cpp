// 4.9 — Boolean Variables
//
// A Boolean variable can store only two possible values:
// true or false.
//
// The keyword used to declare a Boolean variable is bool.
//
// Examples:
//
// bool isStudent { true };
// bool isRaining { false };
//
// Boolean variables can also be changed:
//
// isStudent = false;
//
// Default initialization:
//
// bool isPassed {};
//
// A default-initialized bool is false.
//
// Logical NOT operator (!):
// It reverses a Boolean value.
//
// !true  -> false
// !false -> true
//
// Example:
//
// bool isReady { true };
// bool isNotReady { !isReady }; // false