
 // ============================================================
 // 4.4.2 — DEFINING SIGNED INTEGERS
 // ============================================================

 // Preferred declarations:
 short s {};
 int i {};
 long l {};
 long long ll {};

 // These longer forms are also valid:
 // short int s {};
 // long int l {};
 // long long int ll {};

 // The signed keyword is optional:
 // signed int x {};

 // Best practice:
 // Prefer short, int, long, and long long.
 // Avoid redundant int suffixes and signed prefixes.
