
 // ============================================================
 // 4.4.5 — INTEGER DIVISION
 // ============================================================

 // When both operands are integers, division produces an
 // integer result. Any fractional part is discarded toward zero.

 // Examples:
 // 20 / 4   ->  5
 // 8 / 5    ->  1
 // 13 / 5   ->  2
 // -8 / 5   -> -1
 // -13 / 5  -> -2

 // Integer division does NOT round to the nearest integer.

 // If a fractional result is needed, use floating-point operands:
 // 8.0 / 5.0 -> 1.6

 // REMEMBER:
 // Integer division can lose fractional information.
 // Use it when a whole-number result is intended.
