// 4.11 — Introduction to char
//
// The char data type stores a single character.
//
// Examples:
// 'A'  -> Letter
// '7'  -> Digit character
// '$'  -> Symbol
// ' '  -> Space
//
// Character literals are written inside single quotes.
//
// Examples:
//
// char letter { 'A' };
// char digit  { '7' };
// char symbol { '$' };
//
// Important:
// '7' is a character, not the integer 7.
//
// A char is an integral type.
// Internally, its value is stored as an integer.