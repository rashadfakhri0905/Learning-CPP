// 4.11 — Octal and Hexadecimal Escape Sequences
//
// Escape sequences can also represent characters
// using octal or hexadecimal values.
//
// Octal escape:
// Begins with a backslash followed by an octal number.
//
// Example:
// '\101' represents 'A' in ASCII.
//
// Hexadecimal escape:
// Begins with \x followed by hexadecimal digits.
//
// Example:
// '\x41' represents 'A' in ASCII.
//
// Remember:
// Octal uses base 8.
// Hexadecimal uses base 16.
//
// These are useful when representing characters
// using their numeric character codes.