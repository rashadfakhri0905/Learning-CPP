// 4.11 — Printing char Variables
//
// std::cout prints a char as a character,
// not as its underlying integer value.
//
// Example:
//
// char ch { 'A' };
// std::cout << ch;
//
// Output:
// A
//
// You can also print a character literal directly:
//
// std::cout << 'B';
//
// Output:
// B
//
// If you want to print the numeric ASCII value.