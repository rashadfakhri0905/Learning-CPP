// 4.11 — ASCII
//
// ASCII stands for American Standard Code for Information
// Interchange.
//
// ASCII assigns numeric codes to English letters,
// digits, punctuation, and control characters.
//
// Examples:
//
// ASCII 65 -> 'A'
// ASCII 66 -> 'B'
// ASCII 97 -> 'a'
// ASCII 48 -> '0'
//
// ASCII uses values from 0 to 127.
//
// Printable characters:
// Codes 32 to 126.
//
// Control characters:
// Codes 0 to 31 and 127.
//
// A character is stored internally using its numeric
// character code.
//
// Note:
// ASCII is a character encoding standard, not a C++ data type.