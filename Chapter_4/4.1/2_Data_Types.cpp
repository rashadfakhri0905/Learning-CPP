
 // ============================================================
 // 4.1.1 — BITS, BYTES, AND MEMORY ADDRESSING
 // ============================================================

 // BIT:
 // The smallest unit of information; stores 0 or 1.

 // BYTE:
 // A group of bits operated on as a unit.
 // A byte is 8 bits on modern systems.

 // MEMORY ADDRESS:
 // Identifies a location in memory.
 // In modern systems, each address typically identifies a byte.

 // RAM:
 // Memory used by programs while they execute.

 // MEMORY STORAGE:
 // Computers represent data using sequences of bits.
 // Example: 65 in binary is 01000001 (8-bit representation).

 // KEY POINT:
 // C++ programs usually work with byte-sized memory units.
 // A variable uses memory to store its value.
