
 // ============================================================
 // 4.1.5 — OTHER SETS OF TYPES
 // ============================================================

 // C++ TYPES CAN BE GROUPED INTO THREE MAIN SETS:

 // 1. FUNDAMENTAL TYPES
 // Basic types built into the language.
 // Examples: int, char, bool, double.

 // 2. COMPOUND TYPES
 // Types built from other types or used to create more
 // complex types.
 // Examples: pointers, references, arrays, functions,
 // and classes.

 // 3. STANDARD LIBRARY TYPES
 // Types provided by the C++ standard library.
 // Example: std::string.

 // Standard library types may require including the
 // appropriate header file.

 // EXAMPLE:
 #include <string>

 std::string name { "Hello" };

 // std::string is a standard library type, NOT a
 // fundamental type.

 // KEY POINT:
 // Fundamental and compound types belong to the core language.
 // Standard library types are supplied by the library.
