
 // ============================================================
 // 4.1.3 — FUNDAMENTAL DATA TYPES
 // ============================================================

 // FUNDAMENTAL TYPES:
 // Basic types provided by the C++ language itself.

 // 1. VOID
 // void represents the absence of a type.
 // Commonly used for functions that return no value.

 // 2. BOOLEAN
 // bool stores true or false.

 // 3. CHARACTER TYPES
 // char      : Basic character type.
 // wchar_t   : Wide character type.
 // char8_t   : UTF-8 code-unit type (C++20).
 // char16_t  : UTF-16 code-unit type (C++11).
 // char32_t  : UTF-32 code-unit type (C++11).

 // 4. STANDARD INTEGER TYPES
 // short, int, long, long long
 // Represent whole-number values.
 // Signed and unsigned variants are available.

 // 5. FLOATING-POINT TYPES
 // float       : Floating-point values.
 // double      : Usually offers more precision than float.
 // long double : Precision depends on the implementation.

 // 6. NULL POINTER TYPE
 // std::nullptr_t is the type of nullptr (C++11).
 // Used with null pointers; covered later in pointer lessons.

 // EXAMPLES:
 int count { 10 };
 bool isOpen { false };
 char letter { 'A' };
 double temperature { 36.5 };

 // KEY POINT:
 // Fundamental types are built into the C++ language.
