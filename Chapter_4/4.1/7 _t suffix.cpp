 // NOMENCLATURE:
 // The naming conventions and terminology used in C++.

 // BUILT-IN TYPE:
 // Often used as a synonym for fundamental type.
 // Some authors use it for both fundamental and compound types.

 // Since "built-in type" is used inconsistently, LearnCpp
 // recommends avoiding this term when greater precision matters.

 // STRINGS:
 // A string is a sequence of characters, usually representing text.
 // C++ provides std::string through the standard library.

 // EXAMPLE:
 #include <string>

 std::string message { "Hello, C++!" };

 // std::string is not a fundamental data type.
 // Basic std::string usage is introduced in LearnCpp 5.7.

 // KEY POINT:
 // Use precise type names when explaining C++ concepts.
