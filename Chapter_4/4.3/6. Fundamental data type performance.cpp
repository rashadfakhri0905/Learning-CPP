
 // ============================================================
 // 4.3.6 — FUNDAMENTAL DATA TYPE PERFORMANCE
 // ============================================================

 // Fundamental types are generally efficient to use and copy
 // on modern computers.

 // A smaller type is NOT necessarily faster than a larger type.
 // CPUs may process certain sizes more efficiently than others.

 // Example:
 // An int may perform as fast as, or faster than, a short,
 // depending on the processor and operation.

 // BEST PRACTICE:
 // 1. Choose a type that correctly represents your data.
 // 2. Do not optimize based only on object size.
 // 3. Write readable, maintainable code first.
 // 4. Optimize only when measurements show a meaningful benefit.

 