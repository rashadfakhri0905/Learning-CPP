
 // ============================================================
 // 4.3.1 — OBJECT SIZES
 // ============================================================

 // OBJECT SIZE:
 // The amount of memory occupied by an object, measured in bytes.

 // Most objects occupy more than one byte.
 // Object size depends on its type and the implementation.

 // EXAMPLES (typical sizes on many modern systems):
 // char   -> 1 byte
 // short  -> 2 bytes
 // int    -> 4 bytes
 // double -> 8 bytes

 // A BYTE:
 // A byte is typically 8 bits on modern systems.
 // An object with n bits can represent up to 2^n bit patterns.

 // EXAMPLES:
 // 1 bit  -> 2 possible patterns
 // 2 bits -> 4 possible patterns
 // 8 bits -> 256 possible patterns

 // IMPORTANT:
 // More bits allow more possible representations, but the
 // number of valid values depends on the data type.

 // MEMORY USAGE:
 // Each object uses memory while it exists.
 // Using less memory is not always faster.

 // BEST PRACTICE:
 // Prioritize readable, maintainable code.
 // Optimize memory usage when it provides a meaningful benefit.
