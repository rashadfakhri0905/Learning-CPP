
 // ============================================================
 // 4.3.3 — NOMENCLATURE
 // ============================================================

 // When discussing a type's size, we mean the size of an object
 // of that type, measured in bytes.

 // EXAMPLE:
 // int x {};
 // sizeof(x) gives the size of object x in bytes.

 // For learning purposes, common assumptions include:
 // - A byte contains 8 bits.
 // - Memory is byte-addressable.
 // - Floating-point types use IEEE 754 representations.
 // - The system uses a 32-bit or 64-bit architecture.

 // These are common assumptions, not universal guarantees.

 // KEY POINT:
 // Distinguish between what the C++ standard guarantees
 // and what is merely typical on your system.
