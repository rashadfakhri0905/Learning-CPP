// 4.12 — Introduction to Type Conversion
//
// Type conversion means changing a value from one data type
// into another data type.
//
// Example:
//
// int x { 5 };
// double y { x };
//
// The integer value 5 is converted into a double value 5.0.
//
// C++ performs some conversions automatically.
//
// Other conversions must be requested explicitly.
//
// Two main categories:
//
// 1. Implicit type conversion
//    Conversion performed automatically by C++.
//
// 2. Explicit type conversion
//    Conversion requested by the programmer.
//
// Important:
// Type conversion can sometimes cause information loss.