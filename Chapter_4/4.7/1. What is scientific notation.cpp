// 4.7 — Introduction to Scientific Notation
//
// Scientific notation is a shorter way to write very large
// or very small numbers.
//
// General form:
//
// significand x 10^exponent
//
// Example:
// 1.2 x 10^4 = 12000
//
// Here:
// 1.2 = significand
// 4   = exponent
//
// By convention, scientific notation has exactly one
// non-zero digit before the decimal point.
//
// It makes long numbers easier to read and compare.