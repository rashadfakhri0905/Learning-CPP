// 4.7 — Significant Digits
//
// Significant digits (significant figures) are the meaningful
// digits in a number that indicate its precision.
//
// In scientific notation, the digits in the significand
// are the significant digits.
//
// Examples:
//
// 3.14e0    // 3 significant digits
// 3.14159e0 // 6 significant digits
//
// The more significant digits a number has,
// the more precise it is.
//
// Example:
// 3.14 and 3.14159 have approximately the same value,
// but 3.14159 gives more precision.