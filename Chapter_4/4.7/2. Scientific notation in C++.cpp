// 4.7 — Scientific Notation in C++
//
// C++ uses the letter 'e' or 'E' to represent
// "multiplied by 10 raised to the power of".
//
// Examples:
//
// 1.2e4    = 1.2 x 10^4  = 12000
// 5.3e3    = 5.3 x 10^3  = 5300
// 4.5e2    = 4.5 x 10^2  = 450
//
// Negative exponents represent very small numbers:
//
// 5e-2     = 5 x 10^-2   = 0.05
// 3e-3     = 3 x 10^-3   = 0.003
//
// Both 'e' and 'E' can be used.