// 4.8 — Quick Revision
//
// float       -> typically 4 bytes, 7 significant digits
// double      -> typically 8 bytes, 16 significant digits
// long double -> platform-dependent size and precision
//
// 5.0  -> double literal
// 5.0f -> float literal
// 5.0L -> long double literal
//
// std::setprecision(17):
// Controls the number of significant digits displayed.
//
// Rounding error:
// Happens when a value cannot be represented exactly.
//
// NaN:
// Not a Number.
//
// Inf:
// Infinity.
//
// Best practice:
// Prefer double for ordinary floating point calculations.
// Never assume floating point values are exact.