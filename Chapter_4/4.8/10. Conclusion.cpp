// 4.8 — Conclusion
//
// 1. Floating point types store fractional numbers and
//    extremely large or small values.
//
// 2. C++ provides float, double, and long double.
//
// 3. Floating point literals default to double.
//
// 4. Use f for float literals and L for long double literals.
//
// 5. double is generally preferred over float.
//
// 6. Floating point types have limited precision.
//
// 7. Rounding errors are normal and can affect calculations.
//
// 8. Never assume floating point values are exact.
//
// 9. Be careful when comparing floating point values.
//
// 10. Avoid division by 0.0.
//
// Most important:
// Prefer double for ordinary floating point calculations
// unless you have a specific reason to use another type.