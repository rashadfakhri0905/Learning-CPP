// 4.8 — Floating Point Range
//
// Floating point types can represent much larger and smaller
// values than ordinary integer types.
//
// Typical IEEE 754 ranges:
//
// float:
// Approximately ±1.18 x 10^-38 to ±3.4 x 10^38
//
// double:
// Approximately ±2.23 x 10^-308 to ±1.80 x 10^308
//
// Precision:
// float  -> typically 7 significant digits
// double -> typically 16 significant digits
//
// Important:
// Range and precision are different concepts.
//
// Range = how large or small a value can be.
// Precision = how many significant digits can be represented.