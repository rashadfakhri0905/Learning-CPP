// 4.8 — What Are Floating Point Numbers?
//
// Floating point types are used to store numbers that have
// fractional components or very large/small values.
//
// Examples:
// 4320.0
// -3.33
// 0.01226
//
// The decimal point can "float", meaning the number of digits
// before and after the decimal point can vary.
//
// Floating point types are always signed.
// They can store positive and negative values.