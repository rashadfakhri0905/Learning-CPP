// 4.8 — C++ Floating Point Types
//
// C++ has three fundamental floating point types:
//
// 1. float
//    Single precision.
//    Typically 4 bytes.
//
// 2. double
//    Double precision.
//    Typically 8 bytes.
//
// 3. long double
//    Extended precision.
//    Typically 8, 12, or 16 bytes, depending on the platform.
//
// Important:
// C++ does not guarantee the exact size of these types.
//
// Modern systems commonly use IEEE 754 floating point formats.
//
// Best practice:
// Prefer double over float unless memory usage is a concern.
// Avoid long double unless you have a specific reason to use it.