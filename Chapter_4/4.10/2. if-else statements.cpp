// 4.10 — If-Else Statements
//
// An if-else statement provides two possible execution paths.
//
// Syntax:
//
// if (condition)
//     true_statement;
// else
//     false_statement;
//
// If condition is true:
//     The if statement executes.
//
// If condition is false:
//     The else statement executes.
//
// Example:
//
// int number { 5 };
//
// if (number == 0)
//     std::cout << "The number is zero\n";
// else
//     std::cout << "The number is non-zero\n";
//
// Only one of the two statements executes.
//
// Use if-else when you want to handle both possible outcomes.