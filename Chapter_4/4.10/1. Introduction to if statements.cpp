// 4.10 — Introduction to if Statements
//
// An if statement allows a program to execute a statement
// only when a given condition evaluates to true.
//
// Syntax:
//
// if (condition)
//     statement;
//
// If condition is true:
//     The statement executes.
//
// If condition is false:
//     The statement is skipped.
//
// Example:
//
// int age { 20 };
//
// if (age >= 18)
//     std::cout << "You are an adult\n";
//
// The condition age >= 18 evaluates to true,
// so the message is printed.
//
// Important:
// A condition is an expression that evaluates to a Boolean value.