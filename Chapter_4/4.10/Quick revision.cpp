// 4.10 — Quick Revision
//
// if:
// Executes a statement when a condition is true.
//
// if-else:
// Executes one statement if true and another if false.
//
// else if:
// Checks additional conditions.
//
// Chaining:
// Conditions are checked from top to bottom.
// The first true condition executes.
//
// Boolean functions:
// Can be used directly inside if conditions.
//
// Non-Boolean conditions:
// 0 -> false
// Non-zero -> true
//
// Early return:
// Exits a function immediately when return is executed.
//
// Example:
//
// if (x < 0)
//     return -x;
//
// return x;
//
// Important:
// An if statement controls only ONE statement.
// Multiple statements with a condition will be covered
// later using blocks in lesson 8.2.