// 4.10 — Important If Statement Rules
//
// 1. An if statement condition must be enclosed in parentheses.
//
// 2. An if statement conditionally executes only ONE statement.
//
// 3. An else must be associated with an if statement.
//
// 4. An else if allows multiple conditions to be checked.
//
// 5. Conditions are checked from top to bottom.
//
// 6. Once a condition is true, the remaining chained
//    conditions are skipped.
//
// 7. A Boolean-returning function can be used directly
//    as an if condition.
//
// 8. An early return immediately exits the current function.
//
// Note:
// We will learn how to use braces to conditionally execute
// multiple statements in lesson 8.2.