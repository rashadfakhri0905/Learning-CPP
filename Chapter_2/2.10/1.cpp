                                 // Preprocessor Directives //

// Preprocessor directives are instructions for the preprocessor.

// Key points:
// 1. They start with #.
// 2. They end with a newline, NOT a semicolon.
// 3. They tell the preprocessor to perform text-processing tasks.
// 4. The preprocessor reads the file from top to bottom.
// 5. The preprocessor does NOT understand normal C++ syntax.
//    It follows its own directive syntax.

// Example:
#include <iostream>

// #include is a preprocessor directive.