                                 //Introduction to temporary objects//

/*
-> A temporary object (also sometimes called an anonymous object) is an unnamed object that is used to hold a 
   value that is only needed for a short period of time. Temporary objects are generated by the compiler when 
   they are needed.
*/

//example 

#include <iostream>

int getValueFromUser()
{
 	std::cout << "Enter an integer: ";
	int input{};
	std::cin >> input;

	return input; // return the value of input back to the caller
}

int main()
{
	std::cout << getValueFromUser() << '\n'; // where does the returned value get stored?

	return 0;
}

/*
-> In the above program, the function getValueFromUser() returns the value stored in local variable input back 
   to the caller. Because input will be destroyed at the end of the function, the caller receives a copy of the 
   value so that it has a value it can use even after input is destroyed.
-> The return value is stored in a temporary object. 
-> Temporary objects have no scope at all (this makes sense, since scope is a property of an identifier, and 
   temporary objects have no identifier).
-> Temporary objects are destroyed at the end of the full expression in which they are created. This means 
   temporary objects are always destroyed before the next statement executes.
-> In modern C++, the compiler will often skip creating the temporary and just initialize the variable directly 
   with the return value.
*/